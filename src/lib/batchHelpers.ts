export function mergeBatchesList(current: BatchItem[], incoming: any[]): BatchItem[] {
  const map = new Map<string, BatchItem>();
  for (const item of current) {
    if (item?.id) map.set(String(item.id), item);
  }
  for (const raw of incoming || []) {
    const id = String(raw?.id || raw?._id || '').trim();
    if (!id) continue;
    const prev = map.get(id);
    const thumb =
      raw?.thumbnail && raw.thumbnail !== '/default-thumbnail.png'
        ? String(raw.thumbnail)
        : prev?.thumbnail || String(raw?.thumbnail || '/default-thumbnail.png');
    map.set(id, {
      id,
      title: String(raw?.title || raw?.name || prev?.title || 'Course Batch'),
      thumbnail: thumb,
    });
  }
  return Array.from(map.values());
}

export function getBatchAudienceMeta(title: string): {
  medium: string;
  audience: string;
  strikePrice: string;
} {
  const lower = (title || '').toLowerCase();
  const isEnglish = lower.includes('english medium') || lower.includes('english');
  const isUp = lower.includes('up board');

  let audience = 'For Bihar Board & Hindi Medium Students';
  if (lower.includes('cuet')) {
    audience = 'For CUET 2026 All Board Aspirants';
  } else if (lower.includes('polytechnic')) {
    audience = 'For Polytechnic Entrance Students';
  } else if (isUp && isEnglish) {
    audience = 'For UP Board English Medium Students';
  } else if (isUp) {
    audience = 'For UP Board Students (Hindi Medium)';
  } else if (isEnglish) {
    audience = 'For Class English Medium Students';
  } else if (lower.includes('12th')) {
    audience = 'For Class 12th Board Exam Students';
  } else if (lower.includes('11th')) {
    audience = 'For Class 11th Foundation Students';
  } else if (lower.includes('10th')) {
    audience = 'For Class 10th Board Exam Students';
  } else if (lower.includes('9th')) {
    audience = 'For Class 9th Foundation Students';
  }

  return {
    medium: isEnglish ? 'English' : 'Hindi',
    audience,
    strikePrice: lower.includes('crash') ? '₹ 1,999' : '₹ 4,999',
  };
}
